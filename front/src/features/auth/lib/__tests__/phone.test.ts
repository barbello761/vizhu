import { describe, expect, it } from 'vitest';

import { formatPhone, normalizePhone } from '../phone';

describe('normalizePhone', () => {
  it.each([
    ['+7 999 123-45-67', '79991234567'],
    ['8 (999) 123-45-67', '79991234567'],
    ['79991234567', '79991234567'],
    ['89991234567', '79991234567'],
    ['9991234567', '79991234567'],
    ['+7(999)1234567', '79991234567'],
  ])('приводит %s к %s', (input, expected) => {
    expect(normalizePhone(input)).toBe(expected);
  });

  it.each([
    ['', 'пустая строка'],
    ['999123456', 'девять цифр'],
    ['999123456789', 'двенадцать цифр'],
    ['19991234567', 'одиннадцать цифр не с 7 и не с 8'],
    ['не номер', 'текст без цифр'],
  ])('возвращает null для %s (%s)', (input) => {
    expect(normalizePhone(input)).toBeNull();
  });
});

describe('formatPhone', () => {
  it('разбивает нормализованный номер на группы', () => {
    expect(formatPhone('79991234567')).toBe('+7 999 123 45 67');
  });

  it('возвращает строку как есть, если формат неожиданный', () => {
    expect(formatPhone('12345')).toBe('12345');
  });
});

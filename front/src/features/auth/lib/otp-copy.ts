import { formatPhone } from './phone';

/**
 * Тексты экранов ввода одноразового кода. Код сейчас приходит голосовым
 * звонком (SMSC, робот диктует цифры), а не СМС — все экраны берут формулировки
 * отсюда, чтобы при смене канала доставки правка была в одном месте.
 */

const target = (phone?: string | null) => (phone ? `номер ${formatPhone(phone)}` : 'ваш номер');

/** Подзаголовок экрана ввода кода: что сейчас произойдёт. */
export const otpCallHint = (phone?: string | null) =>
  `Мы позвоним на ${target(phone)} и продиктуем код`;

/** Объявление скринридеру при открытии экрана ввода кода. */
export const otpCallAnnouncement = (phone?: string | null) =>
  `Введите код. Мы позвоним на ${target(phone)} и продиктуем его.`;

/** Подпись группы полей кода. */
export const otpCodeLabel = (length: number) => `Код из звонка, ${length} цифры`;

/** Доступное имя формы ввода кода. */
export const OTP_FORM_LABEL = 'Форма ввода кода из звонка';

/** Ошибка, когда бэк не смог инициировать звонок. */
export const OTP_SEND_FAILED = 'Не удалось позвонить с кодом. Попробуйте позже.';
